import { describe, expect, it } from "vitest";
import type { RunIdentity } from "../../src/types.js";
import {
  branchName,
  identityProblem,
  prBlock,
  readBranchName,
  readPrBlock,
  readTrailers,
  withTrailers,
} from "../../src/worktrees/index.js";

const full: RunIdentity = {
  runId: "run-7f3a",
  taskId: "task-42",
  agent: "codex",
  model: "gpt-6.1-sol",
  account: "Pro 20x",
  conversationId: "conv_01HZX.9",
};

const bare: RunIdentity = { runId: "r1", taskId: "t1", agent: "claude" };

describe("run identity", () => {
  it("reads the ids back from the branch name", () => {
    expect(branchName(full)).toBe("xatlas/task-42/codex-run-7f3a");
    expect(readBranchName(branchName(full))).toEqual({
      taskId: "task-42",
      agent: "codex",
      runId: "run-7f3a",
    });
    expect(readBranchName(`refs/heads/${branchName(bare)}`)).toEqual({
      taskId: "t1",
      agent: "claude",
      runId: "r1",
    });
  });

  it("reads the whole identity back from the trailers and from the pull request block", () => {
    for (const identity of [full, bare]) {
      expect(readTrailers(withTrailers("Fix the thing", identity))).toEqual(identity);
      expect(readPrBlock(prBlock(identity))).toEqual(identity);
    }
  });

  it("adds the trailers to a message with no body as a block of their own", () => {
    expect(withTrailers("Fix the thing\n", bare)).toBe(
      "Fix the thing\n\nXatlas-Run: r1\nXatlas-Task: t1\nXatlas-Agent: claude",
    );
  });

  it("puts the trailers after Co-Authored-By in the same block", () => {
    const message =
      "Add dark mode\n\nThe settings page gets a switch.\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n";
    const stamped = withTrailers(message, bare);
    expect(stamped).toBe(
      "Add dark mode\n\nThe settings page gets a switch.\n\nCo-Authored-By: Claude <noreply@anthropic.com>\nXatlas-Run: r1\nXatlas-Task: t1\nXatlas-Agent: claude",
    );
    expect(readTrailers(stamped)).toEqual(bare);
  });

  it("changes nothing when the message is stamped twice", () => {
    const once = withTrailers("Add dark mode\n\nCo-Authored-By: A <a@b.c>", full);
    expect(withTrailers(once, full)).toBe(once);
    // Even a message whose trailers are in another order, or have other trailers after them.
    const reordered =
      "Subject\n\nXatlas-Agent: claude\nXatlas-Task: t1\nXatlas-Run: r1\nSigned-off-by: A <a@b.c>";
    expect(withTrailers(reordered, bare)).toBe(reordered);
  });

  it("replaces another run's trailers rather than naming two runs", () => {
    const other = withTrailers("Subject\n\nCo-Authored-By: A <a@b.c>", full);
    const restamped = withTrailers(other, bare);
    expect(readTrailers(restamped)).toEqual(bare);
    expect(restamped.match(/Xatlas-Run:/g)).toHaveLength(1);
    expect(restamped).not.toContain("Xatlas-Model");
    expect(restamped).toContain("Co-Authored-By: A <a@b.c>");
  });

  it("doesn't take a subject that looks like a trailer for a trailer block", () => {
    expect(withTrailers("fix: crash on start", bare)).toBe(
      "fix: crash on start\n\nXatlas-Run: r1\nXatlas-Task: t1\nXatlas-Agent: claude",
    );
    expect(readTrailers("Xatlas-Run: r1\nXatlas-Task: t1\nXatlas-Agent: claude")).toBeUndefined();
  });

  it("starts a new block when the last paragraph is prose", () => {
    const stamped = withTrailers("Subject\n\nSee: the notes below.\nAnd more words here.", bare);
    expect(stamped).toBe(
      "Subject\n\nSee: the notes below.\nAnd more words here.\n\nXatlas-Run: r1\nXatlas-Task: t1\nXatlas-Agent: claude",
    );
  });

  it("refuses a message with no subject", () => {
    expect(() => withTrailers("  \n", bare)).toThrow(/subject/);
  });

  it("reads the pull request block from a body with other text and Windows line endings", () => {
    const body = `## Summary\r\nAdds dark mode.\r\n\r\n${prBlock(full).replace(/\n/g, "\r\n")}\r\n\r\nGenerated by xatlas`;
    expect(readPrBlock(body)).toEqual(full);
    expect(readPrBlock("No block here")).toBeUndefined();
    // A value holding the end marker doesn't cut the block short.
    const tricky = { ...full, account: "<!-- /xatlas-run --> Xatlas-Run: other" };
    expect(readPrBlock(prBlock(tricky))).toEqual(tricky);
    expect(readPrBlock("<!-- xatlas-run -->\nXatlas-Run: r1\n")).toBeUndefined();
  });

  it("round-trips odd but valid ids", () => {
    const odd: RunIdentity = {
      runId: "0.9_RC-1",
      taskId: "T_2026.11.15-a",
      agent: "opencode",
      model: "z-ai/glm-5: high",
      account: "team · Ultra",
    };
    expect(identityProblem(odd)).toBeUndefined();
    expect(readBranchName(branchName(odd))).toEqual({
      taskId: odd.taskId,
      agent: "opencode",
      runId: odd.runId,
    });
    expect(readTrailers(withTrailers("Subject", odd))).toEqual(odd);
    expect(readPrBlock(prBlock(odd))).toEqual(odd);
  });

  it("refuses ids and names that would make a bad ref or break a trailer", () => {
    const bad: Partial<RunIdentity>[] = [
      { runId: "" },
      { runId: "a/b" },
      { runId: "a..b" },
      { runId: "a.lock" },
      { runId: "ends." },
      { runId: "-flag" },
      { runId: ".hidden" },
      { runId: "has space" },
      { runId: "a@{1}" },
      { runId: "ünï" },
      { runId: "x".repeat(101) },
      { taskId: "t:1" },
      { taskId: "t~1" },
      { agent: "evil" as RunIdentity["agent"] },
      { model: "" },
      { model: "two\nlines" },
      { model: " padded" },
      { account: "tab\there" },
      { conversationId: "x".repeat(201) },
    ];
    for (const change of bad) {
      const identity = { ...bare, ...change } as RunIdentity;
      expect(identityProblem(identity), JSON.stringify(change)).toBeDefined();
      expect(() => branchName(identity)).toThrow(/Invalid run identity/);
      expect(() => withTrailers("Subject", identity)).toThrow(/Invalid run identity/);
      expect(() => prBlock(identity)).toThrow(/Invalid run identity/);
    }
  });

  it("reads nothing from text that isn't a valid stamp", () => {
    expect(readBranchName("main")).toBeUndefined();
    expect(readBranchName("xatlas/t1/evil-r1")).toBeUndefined();
    expect(readBranchName("xatlas/t1/claude-a..b")).toBeUndefined();
    expect(readBranchName("xatlas/a/b/claude-r1")).toBeUndefined();
    expect(readTrailers("Subject\n\nXatlas-Run: r1\nXatlas-Agent: claude")).toBeUndefined();
    expect(
      readTrailers("Subject\n\nXatlas-Run: r 1\nXatlas-Task: t1\nXatlas-Agent: claude"),
    ).toBeUndefined();
    expect(
      readTrailers("Subject\n\nXatlas-Run: r1\nXatlas-Task: t1\nXatlas-Agent: robot"),
    ).toBeUndefined();
  });

  it("matches trailer keys without regard to case, as git does", () => {
    expect(
      readTrailers("Subject\n\nxatlas-run: r1\nXATLAS-TASK: t1\nXatlas-agent: claude"),
    ).toEqual(bare);
  });
});
